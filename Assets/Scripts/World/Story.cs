namespace ToxicWasteland
{
    /// <summary>
    /// Все тексты сюжета в одном месте — чтобы Данилу и Ефиму было удобно их править.
    /// Сейчас это черновые тексты-заглушки.
    /// </summary>
    public static class Story
    {
        public const string HeroName = "Герой";

        public static readonly string[] IntroLines =
        {
            "Мир задохнулся в собственном яде.",
            "Воздух стал токсичным. Шторма приходят всё чаще, а людей почти не осталось.",
            "Я потерял всех, кто был мне дорог.",
            "Этой ночью шторм загнал меня в подвал разрушенного дома, где когда-то жил мой дед...",
        };

        public static Dialogue GrandfatherDiary()
        {
            const string D = "Дневник деда";
            return new Dialogue()
                .Say(D, "«Если ты читаешь это — значит, я не успел. Катастрофу устроили не боги и не случай. Это сделали мы».")
                .Say(D, "«Завод „Химпром-7“ годами сбрасывал отходы. Когда фильтры отказали, облако накрыло всё за одну ночь».")
                .Say(D, "«Я собрал устройство. Оно очищает пространство вокруг себя — на три метра, не больше. Но если найти источник...»")
                .Say(D, "(Последние страницы вырваны.)")
                .Say(HeroName, "Дед знал, как это остановить. Я должен найти недостающие страницы.");
        }

        public static Dialogue Marta()
        {
            const string M = "Марта";
            var d = new Dialogue();
            d.Ask(M, "Живой... Давно я не видела живых после шторма. Куда идёшь, парень?",
                new DialogueChoice(Tone.Neutral, "Иду на восток. Ищу кое-что.", 1),
                new DialogueChoice(Tone.Positive, "Рад, что кто-то уцелел. Тебе нужна помощь?", 2),
                new DialogueChoice(Tone.Negative, "Не твоё дело, старуха.", 3));
            d.Say(M, "На востоке ворота старого склада. Их держит токсичная завеса — сквозь неё не пройти.", 4);  // 1
            d.Say(M, "Мне бы дожить до утра, сынок. А вот тебе пригодится совет: ворота на востоке закрыты токсичной завесой.", 4); // 2
            d.Say(M, "Грубишь... Ну и иди. Только через завесу у ворот ты всё равно не пройдёшь.", 4); // 3
            d.Say(M, "Говорят, свет разъедает яд. А за завесой — рычаг. Найдёшь, чем по нему ударить.");     // 4
            d.Say(M, "И держись подальше от зелёных ям. Жижа там сжигает до костей.", -1);                   // 5
            return d;
        }

        public const string MerchantGreeting = "Есть лом — есть товар. Нет лома — проходи, не загораживай свет.";
    }
}
